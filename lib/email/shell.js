/**
 * The chrome every outgoing email shares, and the tokens it is built from.
 *
 * Email is not the web. There is no cascade worth relying on, no external
 * stylesheet, no flexbox in Outlook, and a `<style>` block is stripped outright
 * by several clients — so this is tables and inline styles, which is the one
 * arrangement that renders the same in all of them. Everything here is a string
 * builder rather than JSX for the same reason: the output has to be exact, and
 * a renderer that helpfully reorders attributes is a renderer fighting the job.
 *
 * The palette is the site's, read off app/globals.css. Where the site uses an
 * rgba hairline over a surface, this uses the colour that composites to — email
 * clients honour alpha unevenly and a border that vanishes in one of them reads
 * as a broken card rather than as a subtle one.
 */
import { escapeHtml } from '@lib/html'
import { appUrl } from '@lib/site'

export { escapeHtml }

/* --border is rgba(255,255,255,0.08) over --surface #0A0A0A, which composites to
   #1E1E1E. Spelled as the result so no client has to do the maths. */
/* INK and SURFACE are the shell's own — the card and the ground it sits on.
   Only the tokens a template actually reaches for are exported. */
const INK = '#000000'
const SURFACE = '#0A0A0A'
export const SURFACE_2 = '#111111'
export const HAIRLINE = '#1E1E1E'
export const LIME = '#C8FF00'
export const BONE = '#F7F4EF'
export const MUTED = '#8F8F8F'
export const SUBTLE = '#7D7D7D'

/* Geist is a webfont and email cannot load one, so this is the site's own
   fallback chain with the email-safe families appended — the same substitution a
   visitor with webfonts blocked already sees. */
export const SANS =
  "-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif"
export const MONO = "ui-monospace, 'SF Mono', SFMono-Regular, Menlo, Consolas, monospace"

/** Newlines survive as newlines; the rest is escaped. Anything a person typed
    is untrusted and is about to be interpolated into a document — a name with
    an angle bracket in it should arrive as that name, not as a broken table. */
export function escapeParagraphs(value) {
  return escapeHtml(value)
    .split(/\n{2,}/)
    .map((block) => block.replace(/\n/g, '<br />'))
}

/**
 * A button that renders in Outlook too.
 *
 * A styled <a> is ignored by Word's rendering engine, which is what desktop
 * Outlook uses, so the shape comes from a single-cell table and the anchor only
 * carries the colour and the padding.
 */
export function button({ href, label }) {
  return `<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="margin:28px 0 0;">
  <tr>
    <td align="center" bgcolor="${LIME}" style="border-radius:8px;">
      <a href="${escapeHtml(href)}" style="display:inline-block;padding:13px 26px;font-family:${SANS};font-size:15px;font-weight:600;line-height:1;color:${INK};text-decoration:none;border-radius:8px;">${escapeHtml(label)}</a>
    </td>
  </tr>
</table>`
}

/**
 * The mark and the wordmark, as the nav sets them: a 24px lime mark, then the
 * name with `.dev` in the accent.
 *
 * The mark is a hosted PNG. Gmail strips <svg> outright and blocks `data:`
 * sources, so a raster fetched from the site is the only form that survives
 * everywhere — generated by scripts/email-mark.mjs, transparent so it sits on
 * the card rather than carrying its own tile.
 *
 * The wordmark stays type beside it, and that is the point rather than a
 * duplication: most clients block remote images until the reader asks for them,
 * and in that state the alt text and the name still identify the sender. The
 * lockup degrades to what it used to be instead of to an empty box.
 *
 * A two-cell table, not flexbox — Outlook renders through Word and has neither
 * flex nor inline-block alignment worth trusting. `border:0` on the image is
 * for the clients that still underline-box a linked image, and the explicit
 * width and height attributes are for the ones that ignore CSS on <img>.
 */
function wordmark() {
  return `<table role="presentation" cellpadding="0" cellspacing="0" border="0">
  <tr>
    <td style="padding:0 11px 0 0;line-height:0;" valign="middle">
      <img src="${appUrl('/icons/mark-email.png')}" width="24" height="24" alt="" style="display:block;width:24px;height:24px;border:0;outline:none;text-decoration:none;" />
    </td>
    <td valign="middle" style="font-family:${SANS};font-size:19px;font-weight:600;letter-spacing:0.01em;color:${BONE};white-space:nowrap;">nemanjas<span style="color:${LIME};">.dev</span></td>
  </tr>
</table>`
}

/**
 * Wrap a body in the shared card.
 *
 * `preheader` is the line the inbox list shows after the subject. Left unset the
 * client invents one from the first text in the document, which here would be
 * the wordmark — every email previewing as "nemanjas.dev".
 */
export function layout({ title, preheader, body, footer }) {
  return `<!doctype html>
<html lang="en" style="background:${INK};">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<!-- Tells a client the document is designed dark, so the ones that would
     otherwise force-invert it leave it alone. -->
<meta name="color-scheme" content="dark" />
<meta name="supported-color-schemes" content="dark" />
<title>${escapeHtml(title)}</title>
</head>
<body style="margin:0;padding:0;background:${INK};color:${BONE};-webkit-font-smoothing:antialiased;">
<div style="display:none;max-height:0;overflow:hidden;opacity:0;color:transparent;font-size:1px;line-height:1px;">${escapeHtml(preheader)}</div>

<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="background:${INK};">
  <tr>
    <td align="center" style="padding:40px 20px;">

      <table role="presentation" width="560" cellpadding="0" cellspacing="0" border="0" style="width:100%;max-width:560px;background:${SURFACE};border:1px solid ${HAIRLINE};border-radius:14px;">
        <tr>
          <td style="padding:36px 40px 0;">
            ${wordmark()}
          </td>
        </tr>
        <tr>
          <td style="padding:26px 40px 36px;">
            ${body}
          </td>
        </tr>
      </table>

      <table role="presentation" width="560" cellpadding="0" cellspacing="0" border="0" style="width:100%;max-width:560px;">
        <tr>
          <td style="padding:22px 8px 0;font-family:${SANS};font-size:12px;line-height:1.7;color:${SUBTLE};">
            ${footer}
          </td>
        </tr>
      </table>

    </td>
  </tr>
</table>
</body>
</html>`
}

/* The three type styles the bodies are assembled from, so a heading is the same
   heading in every email without each template restating it. */
export const h1 = (text) =>
  `<h1 style="margin:0 0 14px;font-family:${SANS};font-size:25px;font-weight:700;line-height:1.25;letter-spacing:-0.02em;color:${BONE};">${text}</h1>`

export const p = (text, { top = 0 } = {}) =>
  `<p style="margin:${top}px 0 0;font-family:${SANS};font-size:15px;line-height:1.65;color:${MUTED};">${text}</p>`

export const rule = () =>
  `<div style="height:1px;line-height:1px;font-size:0;background:${HAIRLINE};margin:30px 0 0;">&nbsp;</div>`
